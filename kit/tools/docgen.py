"""G7: generate kit/docs/ARCH_V3.md, the rewrite's architecture doc, from the contracts.

  python kit/tools/docgen.py            # writes kit/docs/ARCH_V3.md
  python kit/tools/docgen.py --check    # exit 1 if ARCH_V3.md is stale (CI / before a commit)

Mechanical sections (class chain, milestone plan, per-class symbol tables = doc Part 4, single
writer table = doc Part 6.2) come straight from contracts.json and single_writer.json, so they
can't drift from the code plan. Hand-written prose lives in kit/docs/arch_notes/<Class>.md and
is copied in under its class, marked (UNREVIEWED) until its first line says `reviewed: yes`.
Every symbol gets an anchor `#Class.Symbol`. The legacy doc is never read or modified here.
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter

from common import KIT_DIR, load_json, run_main

OUT = KIT_DIR / "docs" / "ARCH_V3.md"
NOTES = KIT_DIR / "docs" / "arch_notes"


def anchor(cls: str, sym: str) -> str:
    return f'<a id="{cls}.{sym}"></a>'


def _notes(cls: str) -> list[str]:
    p = NOTES / f"{cls}.md"
    if not p.is_file():
        return []
    text = p.read_text(encoding="utf-8").strip().splitlines()
    reviewed = bool(text) and text[0].strip().lower() == "reviewed: yes"
    body = text[1:] if reviewed else text
    return ([] if reviewed else ["> (UNREVIEWED) prose below was written by a model or a draft; check it."]) + body + [""]


def render(contracts: dict, writer: dict) -> str:
    classes = contracts["classes"]
    out = ["# EcholonBot architecture (v3, generated)", "",
           "Generated by `kit/tools/docgen.py` from `kit/contracts/`. Do not edit by hand: edit the contracts or "
           "`kit/docs/arch_notes/<Class>.md`, then re-run docgen.", ""]
    out += ["## 1. Class chain", "", "| Class | Extends | File | Functions | States |", "|---|---|---|---|---|"]
    for name, c in classes.items():
        out.append(f"| [{name}](#{name}) | {c['parent']} | `Classes/{c['file']}` | {len(c['functions'])} | {len(c['states'])} |")
    out += ["", "## 2. Milestone plan", "",
            "Each stub carries `// @STUB(<milestone>)`; a milestone is done when none of its stubs remain.", "",
            "| Milestone | Systems | Stubs |", "|---|---|---|"]
    per_ms = Counter()
    for c in classes.values():
        per_ms.update(f["milestone"] for f in c["functions"])
        per_ms.update(s["milestone"] for s in c["states"] if s["labels"])
    for ms, tags in contracts["milestones"].items():
        out.append(f"| {ms} | {', '.join(tags)} | {per_ms.get(ms, 0)} |")
    aux = sorted(set(per_ms) - set(contracts["milestones"]))
    for ms in aux:
        out.append(f"| {ms} | (aux classes) | {per_ms[ms]} |")
    out += ["", "## 3. Classes (doc Part 4)", ""]
    for name, c in classes.items():
        out += [f'### {name}<a id="{name}"></a>', "", "```unrealscript", c["header"], "```",
                f"Legacy: `{c['legacy']}`. {len(c['vars'])} var statements, {len(c['consts'])} consts, "
                f"{len(c['structs'])} structs, {len(c['enums'])} enums.", ""]
        out += _notes(name)
        if c["states"]:
            out += ["| State | Extends | Labels | Tag | Milestone |", "|---|---|---|---|---|"]
            for s in c["states"]:
                flag = f" **{s['flag']}**" if s.get("flag") else ""
                out.append(f"| {anchor(name, s['name'])}`{s['name']}`{flag} | {s['parent'] or ''} | "
                           f"{', '.join(s['labels']) or '-'} | {s['tag'] or '-'} | {s['milestone']} |")
            out.append("")
        out += ["| Symbol | Signature | Tag | Milestone |", "|---|---|---|---|"]
        for f in c["functions"]:
            qual = f"{f['state']}.{f['name']}" if f["state"] else f["name"]
            sig = f["signature"].replace("|", "\\|")
            out.append(f"| {anchor(name, qual)}`{qual}` | `{sig}` | {f['tag'] or '-'} | {f['milestone']} |")
        out.append("")
    out += ["## 4. Single-writer rules (doc Part 6.2)", "",
            "Enforced by `boundary_auditor.py` (rule B001). Roles: " +
            "; ".join(f"{r} = {', '.join(v[-1:])}" for r, v in writer["roles"].items()) + ".", "",
            "| Variable | Writers | May reset | Rule |", "|---|---|---|---|"]
    fmt = lambda es: ", ".join(f"{e['role']}.{e['function']}" for e in es) or "-"
    for var, g in writer["guarded"].items():
        out.append(f"| `{var}` | {fmt(g.get('writers', []))} | {fmt(g.get('clear', []))} | {g['rule'].replace('|', '/')} |")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(load_json(KIT_DIR / "contracts" / "contracts.json"),
                  load_json(KIT_DIR / "contracts" / "single_writer.json"))
    if a.check:
        cur = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if cur != text:
            print("ARCH_V3.md is stale; run docgen.py", file=sys.stderr)
            return 1
        print("ARCH_V3.md up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"docgen: {OUT.relative_to(KIT_DIR.parent)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    run_main(main)
